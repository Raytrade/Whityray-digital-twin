const PROVIDERS = [
  {
    id: "ai_gateway",
    label: "AI Gateway / Digital Brain",
    env: ["AI_GATEWAY_API_KEY"],
    note: "Used by the current chat and creative endpoints."
  },
  {
    id: "dialogbrain",
    label: "DialogBrain",
    env: ["DIALOGBRAIN_API_KEY", "DIALOGBRAIN_SECRET"],
    note: "Configuration presence only; provider-specific workflow is not yet enabled."
  },
  {
    id: "elevenlabs",
    label: "ElevenLabs voice",
    env: ["ELEVENLABS_API_KEY"],
    note: "Provider slot only; no voice is generated by this status endpoint."
  },
  {
    id: "music",
    label: "Music generation",
    env: ["SUNO_API_KEY"],
    note: "Provider slot only; use an authorized integration and never expose its key in the browser."
  },
  {
    id: "visual",
    label: "Visual / video",
    env: ["VISUAL_PROVIDER_API_KEY"],
    note: "Generic provider slot; configure only after choosing a provider."
  }
];

export default async function handler(req, res) {
  res.setHeader("Cache-Control", "no-store");

  if (req.method !== "GET") {
    res.setHeader("Allow", "GET");
    return res.status(405).json({ error: "Method not allowed" });
  }

  const providers = PROVIDERS.map(({ id, label, env, note }) => ({
    id,
    label,
    configured: env.some((name) => Boolean(process.env[name])),
    note
  }));

  return res.status(200).json({
    identity: "WhityRay Digital Twin",
    providers
  });
}
